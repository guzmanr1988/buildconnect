// Roof perimeter calibration harness — 5-address sample.
//
// Compares three perimeter estimates against the Google Solar API
// buildingInsights response and selects PERIMETER_MULTI_PLANE_BIAS
// so the bbox-derived base errs high vs the legacy 4·sqrt(area) approach
// on every sample address.
//
// Usage:
//   GOOGLE_MAPS_API_KEY=... node scripts/calibrate-perimeter.mjs
//
// Output: prints a markdown table and the recommended bias multiplier.
// Pipe to scripts/perimeter-calibration.md to commit the audit trail.

const API_KEY = process.env.GOOGLE_MAPS_API_KEY || process.env.VITE_GOOGLE_MAPS_API_KEY
if (!API_KEY) {
  console.error('Missing GOOGLE_MAPS_API_KEY (or VITE_GOOGLE_MAPS_API_KEY)')
  process.exit(1)
}

const SQM_TO_SQFT = 10.7639
const M_TO_FT = 3.28084
const EARTH_RADIUS_M = 6371000

// Pre-staged sample: seeded Apex lead-inbox + canonical demo profiles.
// Spans single-rect, L-shape, and complex multi-plane footprints in
// the Miami-Dade / Broward marketplace.
const ADDRESSES = [
  { label: 'Maria Rodriguez — L-0001 (Coral Way)', lat: 25.7514, lng: -80.2587 },
  { label: 'James Thompson — L-0005 (Kendall Dr)', lat: 25.6789, lng: -80.3253 },
  { label: 'Sarah Chen — Homestead', lat: 25.4687, lng: -80.4776 },
  { label: 'Apex Roofing — NW 7th St HQ', lat: 25.7811, lng: -80.2012 },
  { label: 'Las Olas Blvd — Ft Lauderdale', lat: 26.1224, lng: -80.1373 },
]

function haversineMeters(a, b) {
  const toRad = (d) => (d * Math.PI) / 180
  const dLat = toRad(b.lat - a.lat)
  const dLng = toRad(b.lng - a.lng)
  const lat1 = toRad(a.lat)
  const lat2 = toRad(b.lat)
  const x = Math.sin(dLat / 2) ** 2 + Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLng / 2) ** 2
  return 2 * EARTH_RADIUS_M * Math.asin(Math.sqrt(x))
}

function bboxPerimeterFt(bb) {
  const sw = { lat: bb.sw.latitude, lng: bb.sw.longitude }
  const ne = { lat: bb.ne.latitude, lng: bb.ne.longitude }
  const nw = { lat: ne.lat, lng: sw.lng }
  const se = { lat: sw.lat, lng: ne.lng }
  const widthM = haversineMeters(sw, se)
  const heightM = haversineMeters(sw, nw)
  return (2 * widthM + 2 * heightM) * M_TO_FT
}

async function fetchInsights(lat, lng) {
  const url = `https://solar.googleapis.com/v1/buildingInsights:findClosest?location.latitude=${lat}&location.longitude=${lng}&key=${API_KEY}`
  const res = await fetch(url)
  if (!res.ok) throw new Error(`HTTP ${res.status}`)
  return res.json()
}

const rows = []
for (const addr of ADDRESSES) {
  try {
    const json = await fetchInsights(addr.lat, addr.lng)
    const areaSqft = (json.solarPotential?.wholeRoofStats?.areaMeters2 ?? 0) * SQM_TO_SQFT
    const segCount = json.solarPotential?.roofSegmentStats?.length ?? 0
    const bb = json.boundingBox
    if (!bb) {
      rows.push({ ...addr, error: 'no boundingBox', segCount })
      continue
    }
    const sqrtPerim = Math.round(Math.sqrt(areaSqft) * 4)
    const bboxPerim = Math.round(bboxPerimeterFt(bb))
    const ratio = sqrtPerim / bboxPerim
    rows.push({ ...addr, areaSqft: Math.round(areaSqft), segCount, sqrtPerim, bboxPerim, ratio })
  } catch (e) {
    rows.push({ ...addr, error: e.message })
  }
}

const valid = rows.filter((r) => !r.error)
const maxRatio = valid.length ? Math.max(...valid.map((r) => r.ratio)) : 1
const SAFETY = 1.10
const recommended = Math.max(1.15, +(maxRatio * SAFETY).toFixed(2))

console.log('# Roof perimeter calibration\n')
console.log('Generated by `node scripts/calibrate-perimeter.mjs` against Google Solar API buildingInsights.\n')
console.log('| Address | seg# | areaSqft | sqrt·4 (legacy) | bbox-haversine (base) | ratio sqrt/bbox |')
console.log('|---|---|---|---|---|---|')
for (const r of rows) {
  if (r.error) {
    console.log(`| ${r.label} | — | — | — | — | error: ${r.error} |`)
  } else {
    console.log(`| ${r.label} | ${r.segCount} | ${r.areaSqft} | ${r.sqrtPerim} | ${r.bboxPerim} | ${r.ratio.toFixed(3)} |`)
  }
}
console.log('')
console.log(`max ratio sqrt/bbox: ${maxRatio.toFixed(3)}`)
console.log(`safety: ${SAFETY}`)
console.log(`recommended PERIMETER_MULTI_PLANE_BIAS: ${recommended}`)
console.log('')
console.log('Multiplier rule: max(1.15, max_ratio × 1.10) — floor at 1.15 covers the multi-plane drip-edge gap (bbox is footprint, real roof edge runs along every pitched plane); ratio-derived floor guards against regression on samples where the legacy 4·sqrt approximation already over-estimated the bbox footprint perimeter.')
